// One `TableMapping` per pinned table (ARCHITECTURE §6): which `data-src` file and path feeds it,
// and the typed, unit-carrying column contract its rows must satisfy. `rows.ts` holds the row
// builders; `build.ts` joins the two, validates, and writes `src/packs/<pack>/core/tables/`.
//
// Column rules the build enforces (validate.ts):
// - money columns are integer cents (`int`, or a `band` of integers); `cents_per_kwh` may be fractional;
// - a column whose name ends in a unit suffix (`_cents`, `_pct`, `_g`, `_h`, …) declares that unit;
// - `unit` on a `list` is the unit of its elements; `band` members all share the column's unit.

import type { ColumnDef, TableMapping, TableUnit } from "../../src/shared/tables";

/** The default data pack (D26) these tables ship as. */
export const DATA_PACK = "modern-us";

const withDoc = (def: ColumnDef, doc?: string): ColumnDef => (doc ? { ...def, doc } : def);
const text = (doc?: string): ColumnDef => withDoc({ type: "text" }, doc);
const bool = (doc?: string): ColumnDef => withDoc({ type: "bool" }, doc);
const json = (doc: string): ColumnDef => ({ type: "json", doc });
const int = (unit?: TableUnit, doc?: string): ColumnDef => withDoc(unit ? { type: "int", unit } : { type: "int" }, doc);
const num = (unit?: TableUnit, doc?: string): ColumnDef => withDoc(unit ? { type: "number", unit } : { type: "number" }, doc);
const band = (unit: TableUnit, doc?: string): ColumnDef => withDoc({ type: "band", unit }, doc);
const oneOf = (values: string[], doc?: string): ColumnDef => withDoc({ type: "enum", values }, doc);
const ref = (table: string, doc?: string): ColumnDef => withDoc({ type: "ref", ref: table }, doc);
const listOf = (of: "text" | "enum" | "json", extra: { values?: string[]; doc?: string } = {}): ColumnDef =>
  withDoc({ type: "list", of, ...(extra.values ? { values: extra.values } : {}) }, extra.doc);
const opt = (def: ColumnDef): ColumnDef => ({ ...def, optional: true });

